def main():
    OUT.mkdir(exist_ok=True)
    by_name = {c["name"]: c for c in CERTS}
    missing = []
    for c in CERTS:
        if not (ROOT / "CBT-list" / f"{c['slug']}-list.html").exists():
            missing.append(c["slug"])
    n = 0
    total_chars = 0
    for c in CERTS:
        fname, html = build_guide(c, by_name)
        (OUT / fname).write_text(html, encoding="utf-8")
        n += 1
        total_chars += len(html)
    (ROOT / "guides.html").write_text(build_hub(), encoding="utf-8")
    print(f"가이드 {n}개 생성 → guide/  (+ guides.html 허브)")
    print(f"평균 파일 크기: {total_chars//n/1024:.1f} KB")
    if missing:
        print(f"⚠️ CBT-list 미존재 슬러그({len(missing)}): {missing}")
    else:
        print("기출문제 목록 링크: 전 종목 매칭 확인 ✓")


if __name__ == "__main__":
    main()
